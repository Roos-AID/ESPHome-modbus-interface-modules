async def async_setup_entry(
    hass: HomeAssistant,  # noqa: ARG001 - the platform signature
    entry: JanitzaConfigEntry,
    async_add_entities: AddConfigEntryEntitiesCallback,
) -> None:
    """Set up the Janitza sensor platform."""
    runtime_data = entry.runtime_data
    device = runtime_data.readings.device
    async_add_entities(
        _sensor_class(description)(runtime_data, description)
        for description in SENSOR_DESCRIPTIONS
        # A model lacks the sub-systems that only another has, such as the
        # UMG 508 the transformer ratios of the UMG 96RM.
        if getattr(device, description.component, None) is not None
    )


def _sensor_class(
    description: JanitzaSensorDescription,
) -> type[JanitzaSensor | JanitzaTotalSensor]:
    """Pick the entity class a description's semantics ask for."""
    if description.state_class in (
        SensorStateClass.TOTAL,
        SensorStateClass.TOTAL_INCREASING,
    ):
        return JanitzaTotalSensor
    return JanitzaSensor


class JanitzaSensor(JanitzaEntity, SensorEntity):
    """Defines a Janitza sensor."""

    entity_description: JanitzaSensorDescription

    @property
    @override
    def native_value(self) -> StateType:
        value = self.entity_description.value_fn(self.coordinator.device)
        # IntEnum stringifies as the raw int; use the option slug.
        if isinstance(value, IntEnum):
            return value.name.lower()
        return value


class JanitzaTotalSensor(JanitzaEntity, RestoreSensor):
    """Defines a Janitza energy counter, which keeps its value across a restart."""

    entity_description: JanitzaSensorDescription

    @override
    async def async_added_to_hass(self) -> None:
        await super().async_added_to_hass()
        if (last_data := await self.async_get_last_sensor_data()) is None:
            return
        if isinstance(last_data.native_value, (int, float)):
            self._attr_native_value = last_data.native_value

    @property
    @override
    def native_value(self) -> int | float | None:
        value = self.entity_description.value_fn(self.coordinator.device)
        if isinstance(value, (int, float)):
            self._attr_native_value = value
        return cast("int | float | None", self._attr_native_value)


